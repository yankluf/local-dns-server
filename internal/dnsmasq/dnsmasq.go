// Package dnsmasq renders the dnsmasq configuration for the stored records
// and supervises the dnsmasq process.
//
// A/AAAA records go into a hosts file in a folder dnsmasq watches, so adding
// or removing them (including every Docker change) never restarts dnsmasq.
// Wildcards and CNAMEs live in the main config, which dnsmasq only reads at
// startup, so changing those restarts it, no more often than RestartSpacing.
package dnsmasq

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"log"
	"net"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
	"sync"
	"syscall"
	"time"

	"github.com/yankluf/local-dns-server/internal/config"
	"github.com/yankluf/local-dns-server/internal/names"
	"github.com/yankluf/local-dns-server/internal/store"
)

// Root zone DNSSEC trust anchors (KSK-2017 and KSK-2024), from
// https://data.iana.org/root-anchors/root-anchors.xml
var trustAnchors = []string{
	".,20326,8,2,E06D44B80B8F1D39A95C0B0D7C65D08458E880409BBC683457104237C7F8EC8D",
	".,38696,8,2,683D2D0ACB8C9B712A1948B27F741219298D0A450D612C483AF444A4C0FB2B16",
}

// HostsFile is the name of the generated file inside the hosts folder.
const HostsFile = "records.hosts"

var nameRe = regexp.MustCompile(`^(\*\.)?[a-z0-9_-]+(\.[a-z0-9_-]+)*$`)

// Files is a complete generated configuration.
type Files struct {
	Conf  string // main dnsmasq config: settings, wildcards, CNAMEs
	Hosts string // A/AAAA records, hot-reloaded by dnsmasq
}

// Render produces the dnsmasq files for records. Each record is checked again
// right before it's written, as a last line of defense against config
// injection; a record that fails is left out and reported in skipped.
func Render(cfg config.DNSmasq, records []store.Record) (f Files, skipped []error) {
	var b strings.Builder
	b.WriteString("# Generated by LDS (Local DNS Server). Do not edit: changes are overwritten.\n")
	b.WriteString("# Put custom dnsmasq settings in the extra config directory instead.\n\n")

	fmt.Fprintf(&b, "port=%d\n", cfg.Port)
	if len(cfg.Listen) > 0 {
		b.WriteString("bind-interfaces\n")
		for _, l := range cfg.Listen {
			fmt.Fprintf(&b, "listen-address=%s\n", l)
		}
	} else {
		// Listening everywhere: only answer hosts on directly connected
		// networks, so a public interface never becomes an open resolver.
		b.WriteString("local-service\n")
	}
	b.WriteString("pid-file=\n")
	b.WriteString("no-resolv\nno-hosts\ndomain-needed\nbogus-priv\n")
	fmt.Fprintf(&b, "cache-size=%d\n", cfg.CacheSize)
	for _, u := range cfg.Upstreams {
		fmt.Fprintf(&b, "server=%s\n", u)
	}
	if cfg.DNSSEC {
		b.WriteString("dnssec\n")
		for _, a := range trustAnchors {
			fmt.Fprintf(&b, "trust-anchor=%s\n", a)
		}
	}
	if cfg.StopRebind {
		// Drop upstream answers that point at private addresses (protects
		// LAN clients from DNS rebinding); our own zones are exempt.
		b.WriteString("stop-dns-rebind\n")
		for _, z := range cfg.Zones {
			fmt.Fprintf(&b, "rebind-domain-ok=/%s/\n", z)
		}
	}
	for _, z := range cfg.Zones {
		// Answer our zones from local data only; never forward them upstream.
		fmt.Fprintf(&b, "local=/%s/\n", z)
	}
	if cfg.LogQueries {
		b.WriteString("log-queries\n")
	}
	b.WriteString("log-facility=-\n")
	fmt.Fprintf(&b, "hostsdir=%s\n", cfg.HostsDir)
	if cfg.ExtraDir != "" {
		if st, err := os.Stat(cfg.ExtraDir); err == nil && st.IsDir() {
			fmt.Fprintf(&b, "conf-dir=%s,*.conf\n", cfg.ExtraDir)
		}
	}

	var hosts strings.Builder
	hosts.WriteString("# Generated by LDS. A/AAAA records; dnsmasq reloads this file on change.\n")
	var wild, cnames []store.Record
	for _, r := range records {
		if err := safeRecord(r, cfg.Zones); err != nil {
			skipped = append(skipped, err)
			continue
		}
		switch r.Type {
		case store.TypeWildcard:
			wild = append(wild, r)
		case store.TypeA, store.TypeAAAA:
			fmt.Fprintf(&hosts, "%s%s %s\n", comment(r), r.Value, r.Name)
		case store.TypeCNAME:
			cnames = append(cnames, r)
		}
	}
	b.WriteString("\n# Wildcards: the domain and every subdomain. Host records win over these.\n")
	for _, r := range wild {
		fmt.Fprintf(&b, "%saddress=/%s/%s\n", comment(r), strings.TrimPrefix(r.Name, "*."), r.Value)
	}
	b.WriteString("\n# Aliases.\n")
	for _, r := range cnames {
		fmt.Fprintf(&b, "%scname=%s,%s\n", comment(r), r.Name, r.Value)
	}
	return Files{Conf: b.String(), Hosts: hosts.String()}, skipped
}

// safeRecord is the final strict check before a record becomes config text.
func safeRecord(r store.Record, zones []string) error {
	fail := func(why string) error {
		return fmt.Errorf("refusing to write record %q: %s", names.CleanText(r.Name, 80), why)
	}
	if !nameRe.MatchString(r.Name) || len(r.Name) > 255 {
		return fail("unsafe name")
	}
	bare := strings.TrimPrefix(r.Name, "*.")
	if !names.InZones(bare, zones) {
		return fail("outside the configured zones")
	}
	switch r.Type {
	case store.TypeWildcard, store.TypeA, store.TypeAAAA:
		ip, err := names.ParseIP(r.Value)
		if err != nil || ip.String() != r.Value {
			return fail("unsafe IP value")
		}
		if (r.Type == store.TypeWildcard) != strings.HasPrefix(r.Name, "*.") {
			return fail("wildcard mismatch")
		}
	case store.TypeCNAME:
		if strings.HasPrefix(r.Name, "*.") || !nameRe.MatchString(r.Value) || strings.HasPrefix(r.Value, "*.") || !names.InZones(r.Value, zones) {
			return fail("unsafe CNAME")
		}
	default:
		return fail("unknown type")
	}
	return nil
}

func comment(r store.Record) string {
	parts := []string{r.Source}
	if r.Container != "" {
		parts = append(parts, "container="+r.Container)
	}
	if r.Comment != "" {
		parts = append(parts, r.Comment)
	}
	return "# " + names.CleanText(strings.Join(parts, ", "), 300) + "\n"
}

// Status describes the managed dnsmasq process.
type Status struct {
	Enabled     bool      `json:"enabled"`
	Running     bool      `json:"running"`
	LastReload  time.Time `json:"last_reload,omitempty"`
	LastRestart time.Time `json:"last_restart,omitempty"`
	LastError   string    `json:"last_error,omitempty"`
	Degraded    string    `json:"degraded,omitempty"` // set while running a fallback config
}

// Manager writes the config and runs dnsmasq.
type Manager struct {
	cfg config.DNSmasq

	mu          sync.Mutex
	current     Files
	cmd         *exec.Cmd
	exited      chan struct{}
	status      Status
	lastRestart time.Time
}

// NewManager returns a manager for the given settings.
func NewManager(cfg config.DNSmasq) *Manager {
	return &Manager{cfg: cfg, status: Status{Enabled: cfg.Enabled}}
}

func (m *Manager) goodConf() string { return m.cfg.ConfigPath + ".good" }
func (m *Manager) goodHosts() string {
	return filepath.Join(filepath.Dir(m.cfg.ConfigPath), HostsFile+".good")
}
func (m *Manager) hostsPath() string { return filepath.Join(m.cfg.HostsDir, HostsFile) }

// Validate runs `dnsmasq --test` on f without touching the live config.
func (m *Manager) Validate(f Files) error {
	if !m.cfg.Enabled {
		return nil
	}
	if err := os.MkdirAll(m.cfg.HostsDir, 0o755); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(filepath.Dir(m.cfg.ConfigPath), ".validate-*.conf")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.WriteString(f.Conf); err != nil {
		tmp.Close()
		return err
	}
	tmp.Close()
	out, err := exec.Command(m.cfg.Binary, "--test", "--conf-file="+tmp.Name()).CombinedOutput()
	if err != nil {
		msg := strings.TrimSpace(strings.ReplaceAll(string(out), tmp.Name(), "config"))
		return errors.New(names.CleanText(msg, 300))
	}
	return nil
}

// Start brings dnsmasq up with f. If f can't be used, it falls back to the
// last config that worked, and failing that to a config with no records, so
// DNS forwarding keeps working whatever happened to the records.
func (m *Manager) Start(f Files, base Files) {
	orig := m.Apply(f)
	if orig == nil || !m.cfg.Enabled {
		return
	}
	log.Printf("dnsmasq: can't use the current records (%v); trying the last working config", orig)
	conf, cerr := os.ReadFile(m.goodConf())
	hosts, herr := os.ReadFile(m.goodHosts())
	if cerr == nil && herr == nil {
		if err := m.applyForce(Files{Conf: string(conf), Hosts: string(hosts)}); err == nil {
			m.setDegraded("running the last working config; fix the records to recover: " + orig.Error())
			return
		}
	}
	log.Print("dnsmasq: no working config saved; starting with no local records")
	if err := m.applyForce(base); err != nil {
		log.Printf("dnsmasq: even the empty config failed: %v", err)
		return
	}
	m.setDegraded("running without local records because they couldn't be applied")
}

func (m *Manager) setDegraded(msg string) {
	m.mu.Lock()
	m.status.Degraded = msg
	m.mu.Unlock()
}

func (m *Manager) applyForce(f Files) error {
	m.mu.Lock()
	m.current = Files{} // force a rewrite and restart
	m.mu.Unlock()
	return m.Apply(f)
}

// Run keeps dnsmasq alive until ctx is cancelled, then stops it and returns.
func (m *Manager) Run(ctx context.Context) {
	t := time.NewTicker(2 * time.Second)
	defer t.Stop()
	for {
		select {
		case <-ctx.Done():
			m.mu.Lock()
			m.stopLocked()
			m.mu.Unlock()
			return
		case <-t.C:
			// Restart dnsmasq if it died unexpectedly.
			m.mu.Lock()
			if m.cfg.Enabled && m.current.Conf != "" && m.cmd == nil {
				if err := m.startLocked(); err != nil {
					m.status.LastError = err.Error()
				}
			}
			m.mu.Unlock()
		}
	}
}

// Apply makes f live. Host-only changes are picked up by dnsmasq without a
// restart; config changes are validated first, then dnsmasq is restarted (no
// sooner than RestartSpacing after the previous restart).
func (m *Manager) Apply(f Files) error {
	m.mu.Lock()
	confChanged := f.Conf != m.current.Conf || (m.cmd == nil && m.cfg.Enabled)
	hostsChanged := f.Hosts != m.current.Hosts
	wait := time.Until(m.lastRestart.Add(m.cfg.RestartSpacing))
	m.mu.Unlock()
	if !confChanged && !hostsChanged {
		return nil
	}
	if confChanged {
		if err := m.Validate(f); err != nil {
			return m.fail(fmt.Errorf("dnsmasq rejected the new config, keeping the old one: %w", err))
		}
		if wait > 0 {
			time.Sleep(wait) // limit restart frequency
		}
	}

	m.mu.Lock()
	defer m.mu.Unlock()
	if err := os.MkdirAll(m.cfg.HostsDir, 0o755); err != nil {
		return m.fail(err)
	}
	if hostsChanged || m.current.Hosts == "" {
		// Write outside the watched folder, then rename in, so dnsmasq never
		// reads a half-written file.
		tmp := filepath.Join(filepath.Dir(m.cfg.ConfigPath), "."+HostsFile+".tmp")
		if err := store.WriteFileDurable(tmp, []byte(f.Hosts), 0o644); err != nil {
			return m.fail(err)
		}
		if err := os.Rename(tmp, m.hostsPath()); err != nil {
			return m.fail(err)
		}
		_ = store.SyncDir(m.cfg.HostsDir)
	}
	if confChanged {
		if err := store.WriteFileDurable(m.cfg.ConfigPath+".tmp", []byte(f.Conf), 0o644); err != nil {
			return m.fail(err)
		}
		if err := os.Rename(m.cfg.ConfigPath+".tmp", m.cfg.ConfigPath); err != nil {
			return m.fail(err)
		}
		_ = store.SyncDir(filepath.Dir(m.cfg.ConfigPath))
	}
	m.current = f
	m.status.LastReload = time.Now().UTC()
	m.status.LastError = ""
	if !m.cfg.Enabled {
		return nil
	}
	if confChanged {
		m.stopLocked()
		if err := m.startLocked(); err != nil {
			return m.fail(err)
		}
		m.lastRestart = time.Now()
		m.status.LastRestart = m.lastRestart.UTC()
		// Catch a dnsmasq that dies right away (e.g. port 53 already taken).
		exited := m.exited
		m.mu.Unlock()
		select {
		case <-exited:
			m.mu.Lock()
			return m.fail(errors.New("dnsmasq exited right after starting; see the log"))
		case <-time.After(300 * time.Millisecond):
		}
		m.mu.Lock()
	}
	m.status.Degraded = ""
	// Remember this as the last working config.
	_ = store.WriteFileDurable(m.goodConf(), []byte(f.Conf), 0o644)
	_ = store.WriteFileDurable(m.goodHosts(), []byte(f.Hosts), 0o644)
	return nil
}

// Status returns the current process state.
func (m *Manager) Status() Status {
	m.mu.Lock()
	defer m.mu.Unlock()
	s := m.status
	s.Running = m.cmd != nil
	return s
}

// Probe sends a real DNS query to dnsmasq and reports whether it answered.
func (m *Manager) Probe(ctx context.Context) error {
	if !m.cfg.Enabled {
		return nil
	}
	addr := "127.0.0.1"
	if len(m.cfg.Listen) > 0 {
		addr = m.cfg.Listen[0]
	}
	target := net.JoinHostPort(addr, strconv.Itoa(m.cfg.Port))
	r := &net.Resolver{PreferGo: true, Dial: func(ctx context.Context, network, _ string) (net.Conn, error) {
		return (&net.Dialer{}).DialContext(ctx, "udp", target)
	}}
	ctx, cancel := context.WithTimeout(ctx, 2*time.Second)
	defer cancel()
	_, err := r.LookupHost(ctx, "lds-health-check."+m.cfg.Zones[0])
	var dnsErr *net.DNSError
	if err == nil || (errors.As(err, &dnsErr) && dnsErr.IsNotFound) {
		return nil // an answer, even "no such name", means dnsmasq is serving
	}
	return fmt.Errorf("dnsmasq didn't answer a test query: %w", err)
}

func (m *Manager) fail(err error) error {
	m.status.LastError = err.Error()
	return err
}

func (m *Manager) startLocked() error {
	cmd := exec.Command(m.cfg.Binary, "--keep-in-foreground", "--conf-file="+m.cfg.ConfigPath)
	cmd.Stdout = prefixWriter{"dnsmasq: "}
	cmd.Stderr = prefixWriter{"dnsmasq: "}
	if err := cmd.Start(); err != nil {
		return fmt.Errorf("start dnsmasq: %w", err)
	}
	exited := make(chan struct{})
	m.cmd, m.exited = cmd, exited
	go func() {
		err := cmd.Wait()
		close(exited)
		m.mu.Lock()
		defer m.mu.Unlock()
		if m.cmd == cmd { // not a deliberate stop
			m.cmd = nil
			msg := "dnsmasq exited"
			if err != nil {
				msg += ": " + err.Error()
			}
			m.status.LastError = msg + " (restarting)"
			log.Print(msg)
		}
	}()
	log.Printf("dnsmasq started (pid %d)", cmd.Process.Pid)
	return nil
}

func (m *Manager) stopLocked() {
	if m.cmd == nil {
		return
	}
	cmd, exited := m.cmd, m.exited
	m.cmd = nil
	_ = cmd.Process.Signal(syscall.SIGTERM)
	select {
	case <-exited:
	case <-time.After(5 * time.Second):
		_ = cmd.Process.Kill()
		<-exited
	}
}

type prefixWriter struct{ prefix string }

func (p prefixWriter) Write(b []byte) (int, error) {
	for _, line := range bytes.Split(bytes.TrimRight(b, "\n"), []byte("\n")) {
		log.Printf("%s%s", p.prefix, names.CleanText(string(line), 1000))
	}
	return len(b), nil
}
